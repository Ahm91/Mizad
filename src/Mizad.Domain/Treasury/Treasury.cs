using Mizad.Domain.Common;

namespace Mizad.Domain.Treasury;

public enum CashAccountType : byte
{
    Cash = 1,
    Bank = 2,
}

/// <summary>Cash or bank account (D-008). Its balance is never stored — it is Σ(in − out) of its transactions.</summary>
public class CashAccount : AuditableEntity<int>, IHasRowVersion
{
    public string Name { get; set; } = string.Empty;

    public CashAccountType AccountType { get; set; }

    public bool IsDefault { get; set; }

    public bool IsActive { get; set; } = true;

    public byte[] RowVersion { get; private set; } = [];
}

/// <summary>DATABASE_DESIGN §10.4.</summary>
public enum CashTransactionType : byte
{
    SaleReceipt = 1,
    CustomerReceipt = 2,
    CustomerRefund = 3,
    SupplierPayment = 4,
    SupplierRefund = 5,
    Expense = 6,
    OtherReceipt = 7,
    OtherPayment = 8,
    TransferIn = 9,
    TransferOut = 10,
    ShiftOverShort = 11,
    Reversal = 12,
}

/// <summary>Append-only cash movement. Exactly one of <see cref="AmountIn"/>/<see cref="AmountOut"/> is positive.</summary>
public class CashTransaction : LedgerRecord
{
    public int CashAccountId { get; set; }

    public DateTime TxDate { get; set; }

    public decimal AmountIn { get; set; }

    public decimal AmountOut { get; set; }

    public CashTransactionType TxType { get; set; }

    public PaymentMethod PaymentMethod { get; set; }

    public PartyType PartyType { get; set; }

    public int? CustomerId { get; set; }

    public int? SupplierId { get; set; }

    public string SourceDocType { get; set; } = string.Empty;

    public int SourceDocId { get; set; }

    public string DocumentNumber { get; set; } = string.Empty;

    public string Description { get; set; } = string.Empty;

    public int? ShiftId { get; set; }

    public long? ReversalOfId { get; set; }
}

public enum VoucherType : byte
{
    Receipt = 1,
    Payment = 2,
}

/// <summary>Receipt (<c>RC-</c>) or payment (<c>PV-</c>) voucher, for a party or another purpose (BR-062).</summary>
public class CashVoucher : DocumentEntity
{
    public VoucherType VoucherType { get; set; }

    public PartyType PartyType { get; set; }

    public int? CustomerId { get; set; }

    public int? SupplierId { get; set; }

    public int? VoucherReasonId { get; set; }

    public decimal Amount { get; set; }

    public PaymentMethod PaymentMethod { get; set; }

    public int CashAccountId { get; set; }

    public string Description { get; set; } = string.Empty;

    public bool IsAutoGenerated { get; set; }

    public string? OriginDocType { get; set; }

    public int? OriginDocId { get; set; }

    public int? ShiftId { get; set; }
}

public enum VoucherReasonScope : byte
{
    Receipt = 1,
    Payment = 2,
    Both = 3,
}

/// <summary>Whether a non-party voucher reason enters net profit (BR-064).</summary>
public enum ProfitEffect : byte
{
    None = 0,
    OtherIncome = 1,
}

public class VoucherReason : Entity<int>
{
    public string Name { get; set; } = string.Empty;

    public VoucherReasonScope Scope { get; set; } = VoucherReasonScope.Both;

    public ProfitEffect AffectsProfit { get; set; }

    public bool IsActive { get; set; } = true;
}

public class ExpenseCategory : Entity<int>
{
    public string Name { get; set; } = string.Empty;

    public string? IconKey { get; set; }

    public bool IsActive { get; set; } = true;
}

/// <summary>Expense <c>EX-</c> (BR-063). A draft is shown as «معلق».</summary>
public class Expense : DocumentEntity
{
    public int ExpenseCategoryId { get; set; }

    public decimal Amount { get; set; }

    public PaymentMethod PaymentMethod { get; set; }

    public int CashAccountId { get; set; }

    public string? Payee { get; set; }

    public string Description { get; set; } = string.Empty;

    public int? ShiftId { get; set; }
}

/// <summary>Transfer between cash accounts <c>CT-</c> (BR-065).</summary>
public class CashTransfer : DocumentEntity
{
    public int FromAccountId { get; set; }

    public int ToAccountId { get; set; }

    public decimal Amount { get; set; }
}

public enum ShiftStatus : byte
{
    Open = 0,
    Closed = 1,
}

/// <summary>Optional cashier shift (D-029, BR-066).</summary>
public class CashierShift : Entity<int>, IHasRowVersion
{
    public string Number { get; set; } = string.Empty;

    public int UserId { get; set; }

    public int CashAccountId { get; set; }

    public ShiftStatus Status { get; set; }

    public DateTime OpenedAt { get; set; }

    public decimal OpeningFloat { get; set; }

    public DateTime? ClosedAt { get; set; }

    public decimal? ExpectedCash { get; set; }

    public decimal? CountedCash { get; set; }

    public decimal? Difference { get; set; }

    public int? ClosedByUserId { get; set; }

    public string? Notes { get; set; }

    public byte[] RowVersion { get; private set; } = [];
}
